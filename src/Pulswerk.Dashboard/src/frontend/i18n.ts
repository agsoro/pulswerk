let currentLang: string = 'en';

function initI18n(lang?: string): void {
    const saved = localStorage.getItem('plswk_lang');
    if (saved && TRANSLATIONS[saved]) {
        currentLang = saved;
    } else if (lang && TRANSLATIONS[lang]) {
        currentLang = lang;
    } else {
        const browserLang = navigator.language.split('-')[0];
        if (TRANSLATIONS[browserLang]) currentLang = browserLang;
    }
    applyTranslations();
}

function setLanguage(lang: string): void {
    if (!TRANSLATIONS[lang]) return;
    currentLang = lang;
    localStorage.setItem('plswk_lang', lang);
    applyTranslations();
}

function t(key: string): string {
    if (!key) return '';
    return (TRANSLATIONS[currentLang] && TRANSLATIONS[currentLang][key]) || key;
}

function applyTranslations(): void {
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = (el as HTMLElement).dataset.i18n;
        if (!key) return;
        if (el.tagName === 'INPUT' && ((el as HTMLInputElement).type === 'text' || (el as HTMLInputElement).type === 'search')) {
            (el as HTMLInputElement).placeholder = t(key);
        } else {
            el.textContent = t(key);
        }
    });
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
        const titleKey = (el as HTMLElement).dataset.i18nTitle;
        if (titleKey) el.title = t(titleKey);
    });

    // Highlight active language button
    document.querySelectorAll('[id^="lang-"]').forEach(btn => {
        const lang = btn.id.replace('lang-', '');
        btn.classList.toggle('active', lang === currentLang);
    });
}

(window as any).initI18n = initI18n;
(window as any).setLanguage = setLanguage;
(window as any).t = t;
(window as any).applyTranslations = applyTranslations;

export { initI18n, setLanguage, t, applyTranslations, currentLang };
